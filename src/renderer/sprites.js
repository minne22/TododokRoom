const spriteCache = {};
function sprite(name) {
  if (spriteCache[name]) return spriteCache[name];
  const rows = SPRITES[name];
  const w = Math.max(...rows.map(r => r.length)), h = rows.length;
  const c = document.createElement("canvas");
  c.width = w; c.height = h;
  const g = c.getContext("2d");
  rows.forEach((row, y) => [...row].forEach((ch, x) => {
    if (ch === "." || !PALETTE[ch]) return;
    g.fillStyle = PALETTE[ch];
    g.fillRect(x, y, 1, 1);
  }));
  return (spriteCache[name] = c);
}

// A sprite as an <img> source for the HTML parts (HUD, panels), scaled up crisp.
const iconUrlCache = {};
function iconUrl(name, scale = 3) {
  const key = name + "@" + scale;
  if (iconUrlCache[key]) return iconUrlCache[key];
  const s = sprite(name), c = document.createElement("canvas");
  c.width = s.width * scale; c.height = s.height * scale;
  const g = c.getContext("2d");
  g.imageSmoothingEnabled = false;
  g.drawImage(s, 0, 0, c.width, c.height);
  return (iconUrlCache[key] = c.toDataURL());
}

// Draws a sprite with its bottom-centre at (x, y), optionally mirrored.
function drawSprite(g, name, x, y, flip = false) {
  const s = sprite(name);
  const left = Math.round(x - s.width / 2), top = Math.round(y - s.height);
  if (!flip) { g.drawImage(s, left, top); return; }
  g.save();
  g.translate(left + s.width, top);
  g.scale(-1, 1);
  g.drawImage(s, 0, 0);
  g.restore();
}
